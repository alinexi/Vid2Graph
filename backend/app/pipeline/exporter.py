"""Obsidian / Notion-ready Markdown export.

* ``single``: one ``.md`` with every concept as a section and ``[[wiki-links]]``.
* ``vault``: a ``.zip`` of atomic notes (one file per concept) + an index MOC note,
  with YAML frontmatter so Obsidian/Dataview can filter by layer & difficulty.
Every mention becomes a timestamped deep link (``?t=855s`` for YouTube).
"""
from __future__ import annotations

import io
import re
import zipfile
from collections import defaultdict

from app.models.schemas import Edge, Graph, Node
from app.pipeline.chunker import fmt_ts

LAYER_TITLE = {"core": "Core Concepts", "jargon": "Dropped Jargon", "prerequisite": "Implicit Prerequisites"}
LAYER_EMOJI = {"core": "🔵", "jargon": "🟠", "prerequisite": "🟣"}
REL_TEXT = {
    "prerequisite_for": "is a prerequisite for", "compared_with": "compared with", "part_of": "is part of",
    "uses": "uses", "leads_to": "leads to", "contrasts_with": "contrasts with", "example_of": "is an example of",
    "related_to": "related to",
}


def safe_filename(name: str) -> str:
    return re.sub(r'[\\/:*?"<>|#^\[\]]+', "", name).strip() or "note"


def deep_link(graph: Graph, seconds: float, app_url: str) -> str:
    s = int(seconds)
    if graph.media_kind == "youtube" and graph.media_url:
        return f"https://www.youtube.com/watch?v={graph.media_url}&t={s}s"
    return f"{app_url.rstrip('/')}/?graph={graph.id}&t={s}"


def _node_md(graph: Graph, n: Node, edges: list[Edge], by_id: dict[str, Node], app_url: str, heading: str = "##") -> str:
    out = [f"{heading} {n.label}", ""]
    meta = [f"**Layer:** {LAYER_EMOJI[n.layer]} {LAYER_TITLE[n.layer]}", f"**Difficulty:** {n.difficulty}"]
    if n.aliases:
        meta.append("**Also known as:** " + ", ".join(n.aliases))
    out.append("  \n".join(meta))
    out.append("")
    if n.eli5:
        out += ["### ELI5", n.eli5, ""]
    if n.summary:
        out += ["### In this video", n.summary, ""]
    if n.mentions:
        out.append("### Mentions")
        for m in sorted(n.mentions, key=lambda m: m.start):
            quote = f" — _{m.snippet.strip()}_" if m.snippet else ""
            out.append(f"- [{fmt_ts(m.start)}]({deep_link(graph, m.start, app_url)}){quote}")
        out.append("")
    outgoing = [e for e in edges if e.source == n.id and e.target in by_id]
    incoming = [e for e in edges if e.target == n.id and e.source in by_id]
    if outgoing or incoming:
        out.append("### Connections")
        for e in outgoing:
            out.append(f"- {REL_TEXT.get(e.relation, e.relation)} [[{by_id[e.target].label}]]")
        for e in incoming:
            out.append(f"- [[{by_id[e.source].label}]] {REL_TEXT.get(e.relation, e.relation)} this")
        out.append("")
    return "\n".join(out)


def _frontmatter(graph: Graph, n: Node) -> str:
    aliases = "".join(f"\n  - \"{a}\"" for a in n.aliases)
    return (f"---\nsource: \"{graph.title}\"\nlayer: {n.layer}\ndifficulty: {n.difficulty}\n"
            f"aliases:{aliases or ' []'}\ntags:\n  - vid2graph\n  - {n.layer}\n---\n")


def export_markdown(graph: Graph, app_url: str = "http://localhost:3000") -> str:
    by_id = {n.id: n for n in graph.nodes}
    out = [f"# {graph.title}", ""]
    if graph.source_url:
        out.append(f"Source: <{graph.source_url}>  ")
    out.append(f"Generated by Vid2Graph · {graph.stats.nodes} concepts · {graph.stats.edges} relations · "
               f"{fmt_ts(graph.duration)} long")
    out.append("")
    if graph.description:
        out += [graph.description, ""]
    out += ["## Map of Content", ""]
    groups: dict[str, list[Node]] = defaultdict(list)
    for n in graph.nodes:
        groups[n.layer].append(n)
    for layer in ("core", "jargon", "prerequisite"):
        if groups[layer]:
            out.append(f"### {LAYER_EMOJI[layer]} {LAYER_TITLE[layer]}")
            for n in sorted(groups[layer], key=lambda n: n.label.lower()):
                out.append(f"- [[{n.label}]] · {n.difficulty}")
            out.append("")
    out += ["---", ""]
    for layer in ("core", "jargon", "prerequisite"):
        for n in sorted(groups[layer], key=lambda n: (n.mentions[0].start if n.mentions else 1e9)):
            out.append(_node_md(graph, n, graph.edges, by_id, app_url))
            out.append("")
    return "\n".join(out)


def export_vault_zip(graph: Graph, app_url: str = "http://localhost:3000") -> bytes:
    by_id = {n.id: n for n in graph.nodes}
    folder = safe_filename(graph.title)[:60]
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        index = [f"# {graph.title}", ""]
        if graph.source_url:
            index.append(f"Source: <{graph.source_url}>\n")
        if graph.description:
            index += [graph.description, ""]
        for layer in ("core", "jargon", "prerequisite"):
            nodes = [n for n in graph.nodes if n.layer == layer]
            if not nodes:
                continue
            index.append(f"## {LAYER_EMOJI[layer]} {LAYER_TITLE[layer]}")
            for n in sorted(nodes, key=lambda n: n.label.lower()):
                index.append(f"- [[{n.label}]]")
            index.append("")
        z.writestr(f"{folder}/{safe_filename(graph.title)} (MOC).md", "\n".join(index))
        for n in graph.nodes:
            body = _frontmatter(graph, n) + "\n" + _node_md(graph, n, graph.edges, by_id, app_url, heading="#")
            z.writestr(f"{folder}/{safe_filename(n.label)}.md", body)
    return buf.getvalue()
