"""Deterministic stand-in for an LLM.

Used by the test-suite and by ``VID2GRAPH_LLM_PROVIDER=mock`` so the whole pipeline
(ingest → chunk → extract → resolve → export) can be exercised with no model
installed. It is intentionally simple: it finds Capitalised Phrases in the chunk text
and treats them as concepts.
"""
from __future__ import annotations

import re
from typing import Any, Type, TypeVar

from pydantic import BaseModel

T = TypeVar("T", bound=BaseModel)

_MARK = re.compile(r"\[(\d{1,2}:\d{2}(?::\d{2})?)\]")
_PHRASE = re.compile(r"\b(?:[A-Z][A-Za-z0-9\-]+(?:\s+[A-Z][A-Za-z0-9\-]+){0,2})\b")
_STOP = {"The", "This", "That", "We", "So", "And", "But", "If", "When", "In", "It", "I", "You",
         "They", "Our", "What", "Which", "Then", "Now", "Okay", "Yeah", "Well", "Because", "There",
         "Here", "For", "On", "At", "To", "Of", "A", "An", "As", "Is", "Are", "Was", "Were", "Not"}


def _concepts_from_text(text: str, limit: int = 10) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    seen: set[str] = set()
    last_ts = "00:00"
    for token in re.finditer(r"\[(\d{1,2}:\d{2}(?::\d{2})?)\]|([A-Z][A-Za-z0-9\-]+(?:\s+[A-Z][A-Za-z0-9\-]+){0,2})", text):
        if token.group(1):
            last_ts = token.group(1)
            continue
        phrase = token.group(2)
        if phrase.split()[0] in _STOP or len(phrase) < 4 or phrase.lower() in seen:
            continue
        seen.add(phrase.lower())
        start = max(0, token.start() - 60)
        snippet = text[start: token.end() + 60].replace("\n", " ")
        out.append({
            "name": phrase,
            "layer": "core" if len(out) % 3 == 0 else "jargon",
            "timestamp": last_ts,
            "context_snippet": _MARK.sub("", snippet).strip(),
            "what_was_said": f"The speaker mentions {phrase}.",
        })
        if len(out) >= limit:
            break
    return out


def mock_structured(model: Type[T], system: str, user: str) -> T:
    name = model.__name__
    if name == "ChunkExtraction":
        return model.model_validate({"concepts": _concepts_from_text(user)})
    if name == "EnrichmentBatch":
        names = re.findall(r"^- (.+?)(?: — | \(|$)", user, re.M)
        items = [{"name": n, "difficulty": ["beginner", "intermediate", "advanced"][len(n) % 3],
                  "eli5": f"{n}, explained simply: it is a concept the speaker relies on.",
                  "summary": f"How {n} came up in this talk."} for n in names]
        return model.model_validate({"concepts": items})
    if name == "SynthesisBatch":
        names = re.findall(r"^- (.+?)(?: — | \(|$)", user, re.M)
        prereqs = [{"name": f"{n} Fundamentals", "eli5": f"The basics you need before {n}.",
                    "difficulty": "beginner", "prerequisite_for": [n]} for n in names[:2]]
        rels = [{"source": a, "target": b, "relation": "related_to"} for a, b in zip(names, names[1:])]
        return model.model_validate({"prerequisites": prereqs, "relations": rels})
    if name == "ExpansionResult":
        m = re.search(r"Concept: (.+)", user)
        n = m.group(1).strip() if m else "Concept"
        return model.model_validate({"prerequisites": [
            {"name": f"Foundations of {n}", "eli5": f"The groundwork behind {n}.", "difficulty": "beginner",
             "prerequisite_for": [n]},
            {"name": f"{n} Trade-offs", "eli5": f"Why {n} is a balancing act.", "difficulty": "intermediate",
             "prerequisite_for": [n]},
        ]})
    if name == "GraphTitle":
        return model.model_validate({"title": "Mock Knowledge Graph", "summary": "Generated by the mock provider."})
    raise ValueError(f"mock provider has no handler for {name}")


def mock_complete(system: str, user: str) -> str:
    ts = _MARK.findall(user)
    cite = f" [{ts[0]}]" if ts else ""
    return f"(mock answer) Based on the transcript context, the speaker discusses the selected concepts{cite}."
